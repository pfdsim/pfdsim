"""Direct VLE/LLE comparison with Cesari 2017 experimental measurements.

Use the normalized source generated by extract_cesari_phase_equilibria.py.
No parameters are refitted. All methods use SI Table S2 pure-component Psat,
ideal vapor and unit Poynting factor, matching the paper's VLE formulation.
Table 6 has no measured vapor compositions, so y errors are not invented.
The output directory must be new. Runtime NRTL/UNIQUAC are included alongside
the five UNIFAC families; unsupported/missing parameters are explicitly flagged.
"""

from __future__ import annotations

import argparse
import hashlib
from importlib.metadata import version
import json
import math
from pathlib import Path
import sys
import time

import numpy as np
from chemicals.vapor_pressure import Antoine
from scipy.optimize import brentq

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.activity_fitting.benchmark_unifac_runtime_fits import IdentityDatabase, METHOD_FILES, write_csv
from thermodynamics_models.nrtl_uniquac import NRTLThermodynamics, UNIQUACThermodynamics
from thermodynamics_models.unifac_models import (
    UNIFACThermodynamics, UNIFAC2Thermodynamics, UNIFDMDThermodynamics,
    UNIFM2Thermodynamics, UNIFNISTThermodynamics,
)

CLASSES = {"UNIFAC": UNIFACThermodynamics, "UNIFAC2": UNIFAC2Thermodynamics,
           "UNIFDMD": UNIFDMDThermodynamics, "UNIFM2": UNIFM2Thermodynamics,
           "UNIFNIST": UNIFNISTThermodynamics, "NRTL runtime": NRTLThermodynamics,
           "UNIQUAC runtime": UNIQUACThermodynamics}
SOURCE = ROOT / "data/source/activity_fitting/cesari_2017_phase_equilibria.json"
WATER, ETHANOL = "7732-18-5", "64-17-5"


def residual_activities(thermo, pc, temperature, low, high):
    phases = ({pc: low, WATER: 1-low}, {pc: high, WATER: 1-high})
    gamma = [thermo.activity_coefficients(temperature, phase) for phase in phases]
    return [math.log(phases[0][c]*gamma[0][c])-math.log(phases[1][c]*gamma[1][c]) for c in (pc, WATER)]


def vle_metrics(rows):
    good_p = [r for r in rows if r.get("pressure_status") == "ok"]
    good_t = [r for r in rows if r.get("temperature_status") == "ok"]
    result = {"points": len(rows), "pressure_successes": len(good_p), "temperature_successes": len(good_t)}
    if good_p:
        relative = np.array([r["relative_pressure_error"] for r in good_p])
        errors = np.array([r["predicted_pressure_Pa"]-r["P_Pa"] for r in good_p])
        result.update(pressure_RMS_bar=float(np.sqrt(np.mean(errors**2)))/100000,
                      pressure_AARD_percent=float(np.mean(np.abs(relative)))*100,
                      RMS_ln_pressure=float(np.sqrt(np.mean([r["ln_pressure_error"]**2 for r in good_p]))))
    if good_t:
        errors = np.array([r["predicted_T_K"]-r["T_K"] for r in good_t])
        result.update(temperature_RMS_K=float(np.sqrt(np.mean(errors**2))),
                      temperature_MAE_K=float(np.mean(np.abs(errors))),
                      temperature_bias_K=float(np.mean(errors)))
    return result


def lle_metrics(rows):
    predicted = [r for r in rows if r.get("coexistence_status") == "two_liquids"]
    ties = [r for r in rows if "observed_tie_delta_ln_a_pc" in r]
    organic = [r for r in predicted if "x_pc_organic" in r]
    result = {"temperature_records": len(rows), "predicted_two_liquids": len(predicted),
              "no_two_liquids_or_failed": len(rows)-len(predicted), "complete_observed_ties": len(ties)}
    if predicted:
        result["aqueous_x_pc_RMS"] = float(np.sqrt(np.mean([(r["predicted_x_pc_aqueous"]-r["x_pc_aqueous"])**2 for r in predicted])))
        result["aqueous_x_pc_AARD_percent"] = float(np.mean([abs(r["predicted_x_pc_aqueous"]/r["x_pc_aqueous"]-1) for r in predicted]))*100
        result["max_predicted_coexistence_ln_activity_residual"] = max(r["predicted_coexistence_residual"] for r in predicted)
    if organic:
        result["organic_x_pc_RMS"] = float(np.sqrt(np.mean([(r["predicted_x_pc_organic"]-r["x_pc_organic"])**2 for r in organic])))
    if ties:
        values = [r[key] for r in ties for key in ("observed_tie_delta_ln_a_pc", "observed_tie_delta_ln_a_water")]
        result["observed_tie_RMS_delta_ln_activity"] = float(np.sqrt(np.mean(np.square(values))))
    return result


def report(summary):
    lines = ["# Cesari 2017: direct experimental VLE/LLE benchmark", "", summary["protocol"], "",
             "## VLE: Table 6", "", "| Method | Phenolic compound | Points | RMS T / K | Pressure RMS / bar | Pressure AARD / % |", "|---|---|---:|---:|---:|---:|"]
    for method, systems in summary["vle"].items():
        for name, m in systems.items():
            if "temperature_RMS_K" in m:
                lines.append(f"| {method} | {name} | {m['points']} | {m['temperature_RMS_K']:.4f} | {m['pressure_RMS_bar']:.5f} | {m['pressure_AARD_percent']:.3f} |")
    lines += ["", "## LLE: Table 3", "", "| Method | Phenolic compound | T records | Predicted two liquids | Aqueous x RMS | Organic x RMS | Experimental tie RMS delta ln(a) |", "|---|---|---:|---:|---:|---:|---:|"]
    for method, systems in summary["lle"].items():
        for name, m in systems.items():
            aq = f"{m['aqueous_x_pc_RMS']:.6f}" if "aqueous_x_pc_RMS" in m else "unavailable"
            org = f"{m['organic_x_pc_RMS']:.6f}" if "organic_x_pc_RMS" in m else "not reported/unavailable"
            tie = f"{m['observed_tie_RMS_delta_ln_activity']:.4f}" if "observed_tie_RMS_delta_ln_activity" in m else "not reported/unavailable"
            lines.append(f"| {method} | {name} | {m['temperature_records']} | {m['predicted_two_liquids']} | {aq} | {org} | {tie} |")
    lines += ["", "## Interpretation limits", "", "The VLE data are measured bubble temperatures at specified pressure and liquid composition; no vapor compositions were measured. RMS(y) cannot be calculated. Pure saturation correlations are held identical for every model, with the paper's ideal-vapor/unit-Poynting convention. The SI ethanol temperature-unit label is inconsistent with its coefficients; kelvin is required to reproduce its normal boiling point, and this is recorded in the source metadata.", "",
              "LLE tie-line activity residuals use the observed endpoints and require no phase solve or pure-component vapor pressure. Predicted endpoints are obtained with the existing runtime phase-equilibrium solvers and checked for chemical-potential equality. Composition RMS values include successful two-liquid predictions only; missing splits are counted separately. Phenol has only aqueous endpoints reported; those six values are not fabricated into complete tie-lines. SLE points are excluded.", "",
              "Runtime NRTL/UNIQUAC use the currently enabled parameters, which may come from other literature or fits. Their results need not reproduce the paper's own regressions. No model was fitted to these measurements in this investigation. ML/parameter training overlap remains unknown.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", required=True, type=Path)
    args = parser.parse_args()
    output = args.output_dir.resolve()
    output.mkdir(parents=True, exist_ok=False)
    started = time.perf_counter()
    source_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    input_files = [ROOT / "data" / name for name in (
        "nrtl_binary_interactions_cas.json", "uniquac_binary_interactions_cas.json", "uniquac_rq_cas.json",
        *METHOD_FILES.values(), "unifac2/UNIFAC2int.csv", "unifac2/UNIFM2intA.xlsx", "unifac2/UNIFM2intB.xlsx")]
    input_files += [ROOT / name for name in ("thermodynamics_models/nrtl_uniquac.py", "thermodynamics_models/unifac_models.py", "thermodynamics_models/activity.py", "compiled_lle.py")]
    input_hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in input_files}
    source = json.loads(SOURCE.read_text())
    db = IdentityDatabase()
    model_cache, audit = {}, []

    def model_for(method, pc, solvent):
        key = (method, pc, solvent)
        if key not in model_cache:
            try:
                model = CLASSES[method]([pc, solvent], db=db)
                # A reference with no enabled interaction is not an ideal-mixture reference.
                if method == "NRTL runtime" and model._nrtl_interaction_for_components(pc, solvent) is None:
                    raise ValueError("no enabled NRTL interaction")
                if method == "UNIQUAC runtime" and model._uniquac_interaction_for_components(pc, solvent) is None:
                    raise ValueError("no enabled UNIQUAC interaction")
                if method in ("UNIFAC", "UNIFAC2", "UNIFDMD", "UNIFM2", "UNIFNIST") and any("interaction parameters missing" in w for w in model.warnings):
                    raise ValueError("UNIFAC interaction matrix incomplete for this pair")
                model_cache[key] = model
            except (ValueError, KeyError, RuntimeError) as error:
                model_cache[key] = str(error)
        model = model_cache[key]
        if isinstance(model, str):
            raise ValueError(model)
        return model

    def psat(cas, t):
        p = source["vapor_pressure"][cas]
        return Antoine(t, p["A_Pa"], p["B"], p["C_K"], base=p["base"])

    vle_rows, lle_rows = [], []
    for method in CLASSES:
        for measurement in source["vle"]:
            row = {"method": method, **measurement}
            pc, x = row["cas_pc"], row["x_pc"]
            try:
                model = model_for(method, pc, ETHANOL)

                def pressure(t):
                    gamma = model.activity_coefficients(t, {pc: x, ETHANOL: 1-x})
                    return x*gamma[pc]*psat(pc, t)+(1-x)*gamma[ETHANOL]*psat(ETHANOL, t)

                predicted = pressure(row["T_K"])
                if not math.isfinite(predicted) or predicted <= 0:
                    raise ValueError("invalid predicted bubble pressure")
                row.update(pressure_status="ok", predicted_pressure_Pa=predicted,
                           relative_pressure_error=predicted/row["P_Pa"]-1,
                           ln_pressure_error=math.log(predicted/row["P_Pa"]))
                try:
                    t = brentq(lambda t: math.log(pressure(t)/row["P_Pa"]), 200., 500., xtol=1e-8)
                    residual = abs(math.log(pressure(t)/row["P_Pa"]))
                    if residual > 1e-8:
                        raise ValueError("bubble root pressure residual too large")
                    row.update(temperature_status="ok", predicted_T_K=t, bubble_root_ln_pressure_residual=residual)
                except (ValueError, OverflowError, ZeroDivisionError) as error:
                    row["temperature_status"] = str(error)
            except (ValueError, KeyError, RuntimeError, OverflowError, ZeroDivisionError) as error:
                row.update(pressure_status=str(error), temperature_status=str(error))
                audit.append({"method": method, "kind": "VLE", "pc": pc, "reason": str(error)})
            vle_rows.append(row)
        write_csv(output / f"vle_{method.replace(' ', '_')}.csv", [r for r in vle_rows if r["method"] == method])
        print(f"{method}: VLE complete", flush=True)

        for measurement in source["lle"]:
            row = {"method": method, **measurement}
            pc, t, low = row["cas_pc"], row["T_K"], row["x_pc_aqueous"]
            high = row.get("x_pc_organic")
            try:
                model = model_for(method, pc, WATER)
                if high is not None:
                    values = residual_activities(model, pc, t, low, high)
                    row.update(observed_tie_delta_ln_a_pc=values[0], observed_tie_delta_ln_a_water=values[1])
                    feed = .5*(low+high)
                    split, first, second, _ = model.liquid_liquid_equilibrium({pc: feed, WATER: 1-feed}, t, max_iter=150, tol=1e-8)
                    endpoints = (first, second) if split else None
                else:
                    endpoints = model.binary_liquid_coexistence(t, max_iter=150, tol=1e-8)
                if endpoints is None:
                    row["coexistence_status"] = "no two-liquid split"
                else:
                    predicted_low, predicted_high = sorted(p[pc] for p in endpoints)
                    residual = max(abs(v) for v in residual_activities(model, pc, t, predicted_low, predicted_high))
                    if residual > 1e-7 or predicted_high-predicted_low <= 1e-6:
                        raise ValueError(f"invalid coexistence endpoints: residual={residual}")
                    row.update(coexistence_status="two_liquids", predicted_x_pc_aqueous=predicted_low,
                               predicted_x_pc_organic=predicted_high, predicted_coexistence_residual=residual)
            except (ValueError, KeyError, RuntimeError, OverflowError, ZeroDivisionError) as error:
                row["coexistence_status"] = str(error)
                audit.append({"method": method, "kind": "LLE", "pc": pc, "T_K": t, "reason": str(error)})
            lle_rows.append(row)
        write_csv(output / f"lle_{method.replace(' ', '_')}.csv", [r for r in lle_rows if r["method"] == method])
        print(f"{method}: LLE complete", flush=True)

    vle_summary, lle_summary = {}, {}
    for method in CLASSES:
        vle_summary[method] = {"ALL": vle_metrics([r for r in vle_rows if r["method"] == method])}
        lle_summary[method] = {"ALL": lle_metrics([r for r in lle_rows if r["method"] == method])}
        for name in sorted({r["name_pc"] for r in source["vle"]}):
            vle_summary[method][name] = vle_metrics([r for r in vle_rows if r["method"] == method and r["name_pc"] == name])
        for name in sorted({r["name_pc"] for r in source["lle"]}):
            lle_summary[method][name] = lle_metrics([r for r in lle_rows if r["method"] == method and r["name_pc"] == name])
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != source_hash:
        raise RuntimeError("Experimental source changed during benchmark")
    for filename, expected in input_hashes.items():
        if hashlib.sha256((ROOT / filename).read_bytes()).hexdigest() != expected:
            raise RuntimeError(f"Runtime inputs changed during benchmark: {filename}")
    summary = {
        "protocol": "Direct predictions for Cesari 2017 Tables 3 and 6, extracted from NIST ThermoML and checked against the local PDF. Five UNIFAC families and runtime NRTL/UNIQUAC. Same SI Table S2 pure Psat for all methods, ideal vapor/unit Poynting, no fitting. Bubble roots checked by pressure residual; LLE endpoints use existing runtime solvers and are checked by chemical-potential equality.",
        "vle": vle_summary, "lle": lle_summary,
        "source_sha256": source_hash, "experimental_vle_points": len(source["vle"]),
        "runtime_input_sha256": input_hashes,
        "experimental_lle_temperature_records": len(source["lle"]),
        "elapsed_seconds": time.perf_counter()-started,
        "versions": {n: version(n) for n in ("numpy", "scipy", "numba", "rdkit", "chemicals")},
        "model_warnings": {" / ".join(key): model.warnings if not isinstance(model, str) else model for key, model in model_cache.items()},
        "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    write_csv(output / "vle.csv", vle_rows)
    write_csv(output / "lle.csv", lle_rows)
    write_csv(output / "excluded.csv", audit)
    (output / "summary.json").write_text(json.dumps(summary, indent=2, allow_nan=False)+"\n")
    (output / "report.md").write_text(report(summary))
    print(json.dumps({"vle": {m: s["ALL"] for m, s in vle_summary.items()}, "lle": {m: s["ALL"] for m, s in lle_summary.items()}, "elapsed_seconds": summary["elapsed_seconds"]}, indent=2), flush=True)


if __name__ == "__main__":
    main()
