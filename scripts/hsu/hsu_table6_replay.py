print(f"{'compound':22s} {'Pc bar':>7s} {'d_sum':>6s}  per-T: mine% (printed%)")
flagged = []
for name, (groups, points) in DATA.items():
    cas = search_chemical(name).CASs
    pc_bar = Pc_lookup(cas) / 1e5
    a = sum(n * Q[q][0] for q, n in groups.items())
    b = sum(n * Q[q][1] for q, n in groups.items()) * 1e-2
    c = sum(n * Q[q][2] for q, n in groups.items()) * 1e4
    d = sum(n * Q[q][3] for q, n in groups.items())
    cells, gaps = [], []
    for T, eta_exp, d_prt in points:
        eta = math.exp(a + b * T + c / T**2 + d * math.log(pc_bar))
        mine = 100 * (eta / eta_exp - 1)
        cells.append(f"{T}K {mine:+6.1f} ({d_prt:+5.1f})")
        gaps.append(abs(mine - d_prt))
    worst = max(gaps)
    mark = "  <-- INCONSISTENT" if worst > 15 else ""
    if worst > 15:
        flagged.append((name, worst))
    print(f"{name:22s} {pc_bar:7.2f} {d:+6.2f}  " + " | ".join(cells) + mark)
print("\nFlagged (worst |mine - printed| > 15 pts):",
      [f"{n} ({w:.0f})" for n, w in flagged] or "none")
print("Note: gap tolerance covers Pc-source fuzz ~ |d_sum| * ~0.03.")
