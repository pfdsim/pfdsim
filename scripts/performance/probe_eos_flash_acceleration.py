#!/usr/bin/env python3
"""Probe EOS solver acceleration in memory before editing production code.

Examples (output directories must be new)::

    .venv/bin/python scripts/performance/probe_eos_flash_acceleration.py \
        examples/methanol_synthesis.pfd --variants full reuse pure boundary \
        --output /tmp/eos-acceleration 2>&1 | tee /tmp/eos-acceleration.log
    .venv/bin/python scripts/performance/probe_eos_flash_acceleration.py \
        --variants boundary --tests --output /tmp/eos-acceleration-tests \
        2>&1 | tee /tmp/eos-acceleration-tests.log

Variants are cumulative: full substitution, per-flash evaluation reuse,
pure-fluid Gibbs selection without composition iteration, and successful
pure-fluid boundary caching independent of the initial guess. All existing
root validity, material balance, fugacity, and liquid-instability audits stay
active. Numerical changes are experiments until their regression tests pass.
The optional tests run only the focused EOS/LKP/MHV2 files. No random inputs
are generated by this script; the maintained tests explicitly seed theirs.
Each run saves baseline-flash.py and baseline-boundary.py. After production
changes, pass those paths with --source and --boundary-source to reproduce
the original attribution experiment. Without a saved source, an already
optimized working tree defaults to the current implementation only.
"""

from __future__ import annotations

import argparse
from contextlib import contextmanager
import inspect
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import phi_phi
from scripts.performance.diagnose_eos_flash_regression import run

ORIGINAL_FLASH = phi_phi.solve_phi_phi_flash
ORIGINAL_BOUNDARY = phi_phi.solve_phi_phi_boundary
SOURCE = inspect.getsource(ORIGINAL_FLASH)
BOUNDARY_SOURCE = inspect.getsource(ORIGINAL_BOUNDARY)


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f'Production solver changed; inspect probe target: {old}')
    return source.replace(old, new)


def build_flash(variant):
    if variant == 'current':
        return ORIGINAL_FLASH
    if variant == 'safeguarded':
        source = replace_once(SOURCE, '        best, best_residual = list(log_K), math.inf',
            '        best, best_residual = list(log_K), math.inf\n'
            '        damping, previous_log_K, previous_residual = 1., None, math.inf')
        source = replace_once(source,
            "            if not admissible(x, 'liquid') or not admissible(y, 'vapor'):\n"
            "                return None\n            try:\n                changes = equations(log_K)\n"
            "            except numerical_errors as error:\n                invalid_states[:] = [error]\n                return None",
            "            changes = None\n"
            "            if admissible(x, 'liquid') and admissible(y, 'vapor'):\n"
            "                try:\n                    changes = equations(log_K)\n"
            "                except numerical_errors as error:\n                    invalid_states[:] = [error]\n"
            "            if changes is None:\n"
            "                if previous_log_K is not None and damping == 1.:\n"
            "                    log_K = [.5*(a+b) for a, b in zip(previous_log_K, log_K)]\n"
            "                    damping = .5\n                    continue\n                return None")
        source = replace_once(source, '            log_K = [max(-690.0, min(690.0, value + change))',
            '            if residual > previous_residual or (previous_log_K is not None and\n'
            '                    residual > .8*previous_residual and\n'
            '                    sum(change*(a-b) for change, a, b in zip(changes, log_K, previous_log_K)) < 0):\n'
            '                damping = .5\n'
            '            previous_log_K, previous_residual = log_K, residual\n'
            '            log_K = [max(-690.0, min(690.0, value + damping * change))')
        source = replace_once(source, '        w = seed\n        completed = False',
            '        w = seed\n        previous_w, previous_change, damping = None, math.inf, 1.\n        completed = False')
        source = replace_once(source,
            "            if not admissible(w, trial_phase):\n"
            "                completed = True  # This is the wrong physical branch.\n                break\n"
            "            try:\n                phi = log_phi(w, trial_phase)\n"
            "            except numerical_errors:\n                completed = True\n                break",
            "            phi = None\n            if admissible(w, trial_phase):\n"
            "                try:\n                    phi = log_phi(w, trial_phase)\n"
            "                except numerical_errors:\n                    pass\n"
            "            if phi is None:\n"
            "                if previous_w is not None and damping == 1.:\n"
            "                    w = {c: .5*(previous_w[c]+w[c]) for c in thermo.components}\n"
            "                    damping = .5\n                    continue\n"
            "                completed = True\n                break")
        source = replace_once(source, '            if max(abs(target[c]-w[c]) for c in active) < tol:',
            '            change = max(abs(target[c]-w[c]) for c in active)\n'
            '            if change < tol:')
        source = replace_once(source, '            w = target',
            '            if change > previous_change or (previous_w is not None and\n'
            '                    change > .8*previous_change and\n'
            '                    sum((target[c]-w[c])*(w[c]-previous_w[c]) for c in active) < 0):\n'
            '                damping = .5\n'
            '            previous_w, previous_change = w, change\n'
            '            w = target if damping == 1. else {c: .5*(w[c]+target[c]) for c in thermo.components}')
        namespace = dict(vars(phi_phi))
        exec(compile(source, '<probe-eos-safeguarded>', 'exec'), namespace)
        return namespace['solve_phi_phi_flash']
    source = replace_once(SOURCE, 'value + 0.5 * change', 'value + change')
    source = replace_once(source, '0.5*(w[c]+target[c])', 'target[c]')
    if variant in ('reuse', 'pure', 'boundary', 'endpoint', 'cached', 'accelerated'):
        source = replace_once(source, '    invalid_states = []',
            '    invalid_states = []\n    kind_cache, phi_cache, phase_cache = {}, {}, {}')
        source = replace_once(source, '    def kind(composition, phase):\n',
            '    def kind(composition, phase):\n'
            '        key = (phase, tuple(composition[c] for c in thermo.components))\n'
            '        if key in kind_cache:\n            return kind_cache[key]\n')
        source = replace_once(source, '            return thermo._eos_root_kind(T, P, composition, phase)',
            '            value = thermo._eos_root_kind(T, P, composition, phase)\n'
            '            kind_cache[key] = value\n            return value')
        source = replace_once(source, '    def log_phi(composition, phase):\n',
            '    def log_phi(composition, phase):\n'
            '        key = (phase, tuple(composition[c] for c in thermo.components))\n'
            '        if key in phi_cache:\n            return phi_cache[key]\n')
        source = replace_once(source, '        return {c: math.log(values[c]) for c in active}',
            '        result = {c: math.log(values[c]) for c in active}\n'
            '        phi_cache[key] = result\n        return result')
        source = replace_once(source, '    def phases(log_K):\n',
            '    def phases(log_K):\n'
            '        key = tuple(log_K)\n'
            '        if key in phase_cache:\n            return phase_cache[key]\n')
        source = replace_once(source, '        return beta, x, y\n\n    def equations',
            '        result = beta, x, y\n        phase_cache[key] = result\n'
            '        return result\n\n    def equations')
    if variant in ('pure', 'boundary', 'endpoint', 'cached', 'accelerated'):
        source = replace_once(source, '    result = iterate(initial)',
            '    result = iterate(initial) if len(active) > 1 else None')
        source = replace_once(source, "    trial_phase = 'vapor' if reference_phase == 'liquid' else 'liquid'",
            "    if len(active) == 1 and max_iter > 1:\n"
            "        return (0.0 if reference_phase == 'liquid' else 1.0), dict(z), dict(z)\n"
            "    trial_phase = 'vapor' if reference_phase == 'liquid' else 'liquid'")
    if variant in ('endpoint', 'cached', 'accelerated'):
        source = replace_once(source, '    result = iterate(initial) if len(active) > 1 else None',
            '    initial_beta, _, _ = phases([math.log(initial[c]) for c in active])\n'
            '    result = iterate(initial) if len(active) > 1 and 0 < initial_beta < 1 else None')
    if variant == 'accelerated':
        source = replace_once(source, '        w = seed\n        completed = False',
            '        w = seed\n        previous_delta = None\n        fallback = None\n        completed = False')
        source = replace_once(source, "            if not admissible(w, trial_phase):\n",
            "            if fallback is not None and not admissible(w, trial_phase):\n"
            "                w = fallback\n            fallback = None\n"
            "            if not admissible(w, trial_phase):\n")
        source = replace_once(source, '            w = {c: target[c] for c in thermo.components}',
            '            delta = {c: target[c]-w[c] for c in active}\n'
            '            extrapolated = None\n'
            '            if previous_delta is not None:\n'
            '                norm = sum(v*v for v in previous_delta.values())\n'
            '                eigenvalue = sum(delta[c]*previous_delta[c] for c in active) / norm if norm else 0.\n'
            '                if 0. < eigenvalue < .99:\n'
            '                    gain = min(8., eigenvalue/(1.-eigenvalue))\n'
            '                    candidate = {c: target[c]+gain*delta.get(c, 0.) for c in thermo.components}\n'
            '                    if all(v >= 0. for v in candidate.values()):\n'
            '                        extrapolated = normalized(candidate)\n'
            '            previous_delta = delta if extrapolated is None else None\n'
            '            fallback = target if extrapolated is not None else None\n'
            '            w = target if extrapolated is None else extrapolated')
    namespace = dict(vars(phi_phi))
    exec(compile(source, f'<probe-eos-{variant}>', 'exec'), namespace)
    return namespace['solve_phi_phi_flash']


@contextmanager
def variant_scope(variant):
    function = build_flash(variant)
    def cached_flash(thermo, composition, T, P, max_iter, tol):
        z = phi_phi.normalized_eos_composition(thermo.components, composition)
        cache = getattr(thermo, '_probe_flashes', None)
        if cache is None:
            cache = thermo._probe_flashes = {}
        key = (T, P, tuple(z.values()), max_iter, tol)
        entry = cache.get(key)
        if entry is None or not entry[1].issubset(thermo._warning_keys):
            result = function(thermo, z, T, P, max_iter, tol)
            thermo._set_limited_cache(cache, key,
                (result, frozenset(thermo._warning_keys)), limit=1024)
        (beta, x, y), _ = cache[key]
        return beta, dict(x), dict(y)
    def boundary(thermo, composition, fixed, guess, *, kind, variable):
        # Validate the supplied guess even when a previously audited result is
        # available. Only one-active-component results use this experiment.
        import math
        if guess is not None and (not math.isfinite(guess) or guess <= 0):
            return ORIGINAL_BOUNDARY(thermo, composition, fixed, guess, kind=kind, variable=variable)
        z = phi_phi.normalized_eos_composition(thermo.components, composition)
        if sum(v > 0 for v in z.values()) != 1:
            return ORIGINAL_BOUNDARY(thermo, composition, fixed, guess, kind=kind, variable=variable)
        cache = getattr(thermo, '_probe_pure_boundaries', None)
        if cache is None:
            cache = thermo._probe_pure_boundaries = {}
        key = (kind, variable, fixed, tuple(z.values()))
        if key not in cache:
            cache[key] = ORIGINAL_BOUNDARY(thermo, z, fixed, guess, kind=kind, variable=variable)
        return cache[key]
    previous = phi_phi.solve_phi_phi_flash, phi_phi.solve_phi_phi_boundary
    phi_phi.solve_phi_phi_flash = cached_flash if variant == 'cached' else function
    phi_phi.solve_phi_phi_boundary = ORIGINAL_BOUNDARY
    if variant in ('boundary', 'endpoint', 'cached', 'accelerated'):
        phi_phi.solve_phi_phi_boundary = boundary
    try:
        yield
    finally:
        phi_phi.solve_phi_phi_flash, phi_phi.solve_phi_phi_boundary = previous


def check_matrix(points, output, reference=None):
    """Audit seeded binary and ternary states against the unchanged solver."""
    import numpy as np
    from chemical_properties import ChemicalDatabase
    from thermodynamics import create_thermodynamics
    rng = np.random.default_rng(20261020)
    binary = rng.uniform([130., .05, .001], [340., 100., .999], size=(points, 3))
    aqueous = rng.uniform([280., 1., .001], [600., 100., .999], size=(max(1, points//4), 3))
    ternary = [(float(rng.uniform(200., 700.)), float(rng.uniform(1., 250.)), fractions)
               for fractions in rng.dirichlet([1., 1., 1.], size=max(1, points//4))]
    groups = [
        (['CH4', 'C2H6'], ['RK', 'PR', 'SRK', 'PSRK', 'RKSMHV2', 'LKP'],
         [(T, P, [f, 1-f]) for T, P, f in binary]),
        (['CO2', 'water'], ['PR', 'PSRK', 'RKSMHV2'],
         [(T, P, [f, 1-f]) for T, P, f in aqueous]),
        (['H2', 'N2', 'NH3'], ['PR', 'RKS-BM'], ternary),
        (['CH4', 'C2H6', 'H2'], ['PR', 'PSRK', 'RKSMHV2', 'LKP'],
         [(T, P, [f, 1-f, 0.]) for T, P, f in binary[:max(1, points//4)]]),
    ]
    summary = {'seed': 20261020, 'states': 0, 'both_failed': 0, 'new_successes': 0,
               'regressions': [], 'different_equilibria': [],
               'max_material_residual': 0., 'max_log_fugacity_residual': 0.}
    def evaluate(function, thermo, z, T, P):
        try:
            return function(thermo, z, T, P, 100, 1e-9), None
        except Exception as error:
            return None, f'{type(error).__name__}: {error}'
    def gibbs(thermo, result, T, P):
        beta, x, y = result
        total = 0.
        for weight, comp, phase in ((1-beta, x, 'liquid'), (beta, y, 'vapor')):
            if weight > 0:
                phi = thermo.fugacity_coefficients(T, P, comp, phase)
                total += weight*sum(v*math.log(v*phi[c]) for c, v in comp.items() if v > 0)
        return total
    for components, methods, states in groups:
        for method in methods:
            thermo = create_thermodynamics(components, method, ChemicalDatabase(enable_online=False))
            for T, P, fractions in states:
                summary['states'] += 1
                z = dict(zip(components, map(float, fractions)))
                old, _ = evaluate(reference or ORIGINAL_FLASH, thermo, z, T, P)
                new, new_error = evaluate(phi_phi.solve_phi_phi_flash, thermo, z, T, P)
                row = {'method': method, 'T': float(T), 'P': float(P), 'z': z}
                if new is None:
                    if old is None:
                        summary['both_failed'] += 1
                    else:
                        summary['regressions'].append({**row, 'error': new_error})
                    continue
                beta, x, y = new
                material = max(abs((1-beta)*x[c]+beta*y[c]-z[c]) for c in z)
                summary['max_material_residual'] = max(summary['max_material_residual'], material)
                residual = 0.
                if 0 < beta < 1:
                    pl = thermo.fugacity_coefficients(T, P, x, 'liquid')
                    pv = thermo.fugacity_coefficients(T, P, y, 'vapor')
                    residual = max(abs(math.log(x[c]*pl[c]/(y[c]*pv[c]))) for c in z if z[c] > 0)
                    summary['max_log_fugacity_residual'] = max(summary['max_log_fugacity_residual'], residual)
                if material > 1e-9 or residual > 1e-8:
                    summary['regressions'].append({**row, 'material': material, 'fugacity': residual})
                if old is None:
                    summary['new_successes'] += 1
                    continue
                if abs(beta-old[0]) > 1e-6:
                    delta_g = gibbs(thermo, new, T, P)-gibbs(thermo, old, T, P)
                    summary['different_equilibria'].append({**row, 'old_beta': old[0],
                        'new_beta': beta, 'gibbs_difference_RT': delta_g})
                    if delta_g > 1e-8:
                        summary['regressions'].append({**row, 'higher_gibbs_RT': delta_g})
            print('MATRIX', method, components, 'states', summary['states'],
                  'regressions', len(summary['regressions']), flush=True)
            with (output / 'matrix.json').open('w') as stream:
                json.dump(summary, stream, indent=2, allow_nan=False)
    print('MATRIX_SUMMARY', json.dumps({k: v if not isinstance(v, list) else len(v)
                                     for k, v in summary.items()}), flush=True)
    return len(summary['regressions'])


def main():
    global SOURCE, ORIGINAL_FLASH, BOUNDARY_SOURCE, ORIGINAL_BOUNDARY
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('examples', nargs='*', type=Path)
    parser.add_argument('--variants', nargs='+', choices=('current', 'full', 'reuse', 'pure', 'boundary', 'endpoint', 'cached', 'accelerated', 'safeguarded'),
                        default=None)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--source', type=Path,
                        help='Saved baseline-flash.py from a previous probe, for historical comparison')
    parser.add_argument('--boundary-source', type=Path,
                        help='Saved baseline-boundary.py from a previous probe')
    parser.add_argument('--repeats', type=int, default=1)
    parser.add_argument('--tests', action='store_true')
    parser.add_argument('--profile', action='store_true')
    parser.add_argument('--matrix-points', type=int, default=0)
    parser.add_argument('--matrix-reference-source', type=Path,
                        help='Compare the matrix against a saved baseline flash without changing the candidate')
    args = parser.parse_args()
    if args.source:
        SOURCE = args.source.read_text(encoding='utf-8')
        namespace = dict(vars(phi_phi))
        exec(compile(SOURCE, str(args.source), 'exec'), namespace)
        ORIGINAL_FLASH = namespace['solve_phi_phi_flash']
    if args.boundary_source:
        BOUNDARY_SOURCE = args.boundary_source.read_text(encoding='utf-8')
        namespace = dict(vars(phi_phi))
        exec(compile(BOUNDARY_SOURCE, str(args.boundary_source), 'exec'), namespace)
        ORIGINAL_BOUNDARY = namespace['solve_phi_phi_boundary']
    if args.variants is None:
        args.variants = (('current', 'full', 'reuse', 'pure', 'boundary', 'endpoint', 'cached')
                         if 'value + 0.5 * change' in SOURCE else ('current',))
    matrix_reference = None
    if args.matrix_reference_source:
        namespace = dict(vars(phi_phi))
        reference_source = args.matrix_reference_source.read_text(encoding='utf-8')
        exec(compile(reference_source, str(args.matrix_reference_source), 'exec'), namespace)
        matrix_reference = namespace['solve_phi_phi_flash']
    if args.repeats < 1 or (not args.examples and not args.tests and not args.matrix_points):
        parser.error('Positive repeats and at least one example or --tests are required')
    args.output.mkdir(parents=True, exist_ok=False)
    with (args.output / 'baseline-flash.py').open('x') as stream:
        stream.write(SOURCE)
    with (args.output / 'baseline-boundary.py').open('x') as stream:
        stream.write(BOUNDARY_SOURCE)
    if matrix_reference is not None:
        with (args.output / 'matrix-reference-flash.py').open('x') as stream:
            stream.write(reference_source)
    failures = 0
    for variant in args.variants:
        output = args.output / variant
        output.mkdir()
        print('VARIANT', variant, flush=True)
        with variant_scope(variant):
            if args.matrix_points:
                failures += check_matrix(args.matrix_points, output, matrix_reference)
            if args.tests:
                import pytest
                result = pytest.main([
                    'tests/test_phi_phi.py', 'tests/test_cubic_phase_equilibrium.py',
                    'tests/test_lkp.py', 'tests/test_mhv2.py',
                ])
                with (output / 'pytest-result.json').open('x') as stream:
                    json.dump({'exit_code': int(result)}, stream)
                failures += int(result != 0)
            for path in args.examples:
                for repeat in range(args.repeats):
                    report = run(path, 'current', repeat, {}, output, args.profile)
                    failures += int(not report['converged'] or bool(report['errors']))
    return int(failures > 0)


if __name__ == '__main__':
    raise SystemExit(main())
